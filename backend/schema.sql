-- GoRent Supabase/Postgres schema
-- This preserves the original application schema: same table names, column names,
-- relationships, uniqueness rules, defaults, and indexes.

-- User table
CREATE TABLE IF NOT EXISTS "User" (
    user_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone_number VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) DEFAULT 'renter',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Location table
CREATE TABLE IF NOT EXISTS "Location" (
    location_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    address_line1 VARCHAR(100) NOT NULL,
    address_line2 VARCHAR(100),
    city VARCHAR(50) NOT NULL,
    state_region VARCHAR(50) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    country VARCHAR(50) NOT NULL,
    latitude DECIMAL(10, 8),
    longitude DECIMAL(11, 8)
);

-- Vehicle table
CREATE TABLE IF NOT EXISTS "Vehicle" (
    vehicle_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    owner_user_id INTEGER NOT NULL,
    vin VARCHAR(30) NOT NULL UNIQUE,
    license_plate VARCHAR(20) NOT NULL UNIQUE,
    make VARCHAR(50) NOT NULL,
    model VARCHAR(50) NOT NULL,
    year INTEGER NOT NULL,
    color VARCHAR(30),
    mileage INTEGER,
    image VARCHAR(255),
    vehicle_status VARCHAR(20) DEFAULT 'available',
    FOREIGN KEY (owner_user_id) REFERENCES "User"(user_id) ON DELETE CASCADE
);

-- Listing table
CREATE TABLE IF NOT EXISTS "Listing" (
    listing_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    vehicle_id INTEGER NOT NULL,
    location_id INTEGER NOT NULL,
    price_per_day DECIMAL(10, 2) NOT NULL,
    description VARCHAR(300),
    availability_status VARCHAR(20) DEFAULT 'available',
    date_posted TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    image_url VARCHAR(255),
    CONSTRAINT listing_vehicle_id_unique UNIQUE (vehicle_id),
    FOREIGN KEY (vehicle_id) REFERENCES "Vehicle"(vehicle_id) ON DELETE CASCADE,
    FOREIGN KEY (location_id) REFERENCES "Location"(location_id) ON DELETE CASCADE
);

-- Booking table
CREATE TABLE IF NOT EXISTS "Booking" (
    booking_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    listing_id INTEGER NOT NULL,
    renter_user_id INTEGER NOT NULL,
    start_date TIMESTAMP NOT NULL,
    end_date TIMESTAMP NOT NULL,
    booking_status VARCHAR(20) DEFAULT 'pending',
    total_amount DECIMAL(10, 2),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    delivery_location_id INTEGER,
    FOREIGN KEY (listing_id) REFERENCES "Listing"(listing_id) ON DELETE CASCADE,
    FOREIGN KEY (renter_user_id) REFERENCES "User"(user_id) ON DELETE CASCADE,
    FOREIGN KEY (delivery_location_id) REFERENCES "Location"(location_id)
);

-- Payment table
CREATE TABLE IF NOT EXISTS "Payment" (
    payment_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    booking_id INTEGER NOT NULL,
    payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    amount DECIMAL(10, 2) NOT NULL,
    payment_method VARCHAR(30),
    payment_status VARCHAR(30) DEFAULT 'pending',
    transaction_reference VARCHAR(100),
    FOREIGN KEY (booking_id) REFERENCES "Booking"(booking_id) ON DELETE CASCADE
);

-- Revenue table
CREATE TABLE IF NOT EXISTS "Revenue" (
    revenue_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    payment_id INTEGER NOT NULL,
    booking_fee DOUBLE PRECISION,
    commission DOUBLE PRECISION,
    dropoff_fee DOUBLE PRECISION,
    platform_payout DOUBLE PRECISION,
    lister_payout DOUBLE PRECISION,
    payout_date TIMESTAMP,
    FOREIGN KEY (payment_id) REFERENCES "Payment"(payment_id) ON DELETE CASCADE
);

-- Create indexes for better query performance
CREATE INDEX IF NOT EXISTS idx_vehicle_owner ON "Vehicle"(owner_user_id);
CREATE INDEX IF NOT EXISTS idx_listing_vehicle ON "Listing"(vehicle_id);
CREATE INDEX IF NOT EXISTS idx_listing_location ON "Listing"(location_id);
CREATE INDEX IF NOT EXISTS idx_booking_listing ON "Booking"(listing_id);
CREATE INDEX IF NOT EXISTS idx_booking_renter ON "Booking"(renter_user_id);
CREATE INDEX IF NOT EXISTS idx_booking_status ON "Booking"(booking_status);
CREATE INDEX IF NOT EXISTS idx_booking_dates ON "Booking"(start_date, end_date);
CREATE INDEX IF NOT EXISTS idx_payment_booking ON "Payment"(booking_id);
CREATE INDEX IF NOT EXISTS idx_payment_status ON "Payment"(payment_status);
